<?php
declare(strict_types=1);

/**
 * Symo — Gerenciador de Migrações e Seeds (CLI)
 *
 * Uso:
 *   php migrate.php          -> Executa migrações pendentes e seeds iniciais se for primeira execução
 *   php migrate.php --seed   -> Executa seeds de dados iniciais
 *   php migrate.php --status -> Exibe status das migrações
 *   php migrate.php --fresh  -> Recria o banco de dados do zero e roda migrações + seeds
 */

if (php_sapi_name() !== 'cli') {
    die("Este script só pode ser executado via linha de comando (CLI).\n");
}

define('APP_RUNNING', true);
define('APP_ROOT', __DIR__);

require_once __DIR__ . '/config/database.php';

echo "\n==================================================\n";
echo "           Symo — Gerenciador de Banco            \n";
echo "==================================================\n\n";

try {
    // Obtém conexão PDO (criando o banco de dados caso não exista)
    $pdo = Database::getConnection(true);
} catch (Throwable $e) {
    echo "[ERRO CRÍTICO] Falha ao conectar ao banco de dados: " . $e->getMessage() . "\n";
    exit(1);
}

// Garante que a tabela de migrações exista.
$migrationDriver = $pdo->getAttribute(PDO::ATTR_DRIVER_NAME);
$migrationSchema = $migrationDriver === 'pgsql'
    ? "CREATE TABLE IF NOT EXISTS migracoes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        migracao VARCHAR(255) NOT NULL UNIQUE,
        lote INTEGER NOT NULL,
        executado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )"
    : "CREATE TABLE IF NOT EXISTS `migracoes` (
        `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
        `migracao` VARCHAR(255) NOT NULL UNIQUE,
        `lote` INT UNSIGNED NOT NULL,
        `executado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
        INDEX `idx_migracoes_migracao` (`migracao`),
        INDEX `idx_migracoes_lote` (`lote`)
    ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;";
$schemaStatement = $pdo->prepare($migrationSchema);
$schemaStatement->execute();

$args = $argv ?? [];
$isFresh  = in_array('--fresh', $args, true);
$onlySeed = in_array('--seed', $args, true);
$isStatus = in_array('--status', $args, true);

if ($isFresh) {
    if ($migrationDriver === 'pgsql') {
        if (!in_array('--confirmar', $args, true)) {
            echo "[ERRO] --fresh no PostgreSQL/Neon apaga TODOS os dados do banco conectado (DATABASE_URL atual).\n";
            echo "       Rode novamente com '--fresh --confirmar' para confirmar explicitamente esta ação destrutiva.\n";
            exit(1);
        }

        echo "[!] ATENÇÃO: Apagando todo o schema 'public' do banco PostgreSQL/Neon atual (--fresh --confirmar)...\n";
        $pdo->exec('DROP SCHEMA IF EXISTS public CASCADE');
        $pdo->exec('CREATE SCHEMA public');

        $schemaStatement = $pdo->prepare("CREATE TABLE IF NOT EXISTS migracoes (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            migracao VARCHAR(255) NOT NULL UNIQUE,
            lote INTEGER NOT NULL,
            executado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        )");
        $schemaStatement->execute();
        echo "[OK] Schema recriado do zero.\n\n";
    } else {
        echo "[!] ATENÇÃO: Recriando banco de dados completo (--fresh)...\n";
        $config = require __DIR__ . '/config/config.php';
        $dbname = $config['database']['dbname'] ?? 'symo_db';
        $charset = $config['database']['charset'] ?? 'utf8mb4';

        $dropDatabaseStatement = $pdo->prepare("DROP DATABASE IF EXISTS `{$dbname}`");
        $dropDatabaseStatement->execute();
        $createDatabaseStatement = $pdo->prepare("CREATE DATABASE `{$dbname}` CHARACTER SET {$charset} COLLATE utf8mb4_unicode_ci");
        $createDatabaseStatement->execute();
        Database::resetConnection();
        $pdo = Database::getConnection(false);

        $schemaStatement = $pdo->prepare("CREATE TABLE IF NOT EXISTS `migracoes` (
            `id` INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
            `migracao` VARCHAR(255) NOT NULL UNIQUE,
            `lote` INT UNSIGNED NOT NULL,
            `executado_em` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
            INDEX `idx_migracoes_migracao` (`migracao`),
            INDEX `idx_migracoes_lote` (`lote`)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;");
        $schemaStatement->execute();
        echo "[OK] Banco de dados recriado.\n\n";
    }
}

// Função para rodar seeds
function runSeeds(PDO $pdo): void {
    $seedFile = __DIR__ . '/database/seeds/initial_data.php';
    if (file_exists($seedFile)) {
        echo "\n[*] Executando seeds de dados iniciais...\n";
        $seeder = require $seedFile;
        if (is_object($seeder) && method_exists($seeder, 'run')) {
            $seeder->run($pdo);
            echo "[OK] Seeds executados com sucesso!\n";
        }
    }
}

if ($onlySeed) {
    runSeeds($pdo);
    echo "\nConcluído com sucesso.\n";
    exit(0);
}

// 1. Obter histórico de migrações já executadas
$executedStatement = $pdo->prepare("SELECT `migracao` FROM `migracoes`");
$executedStatement->execute();
$executed = $executedStatement->fetchAll(PDO::FETCH_COLUMN);

// 2. Localizar arquivos de migração no diretório
$migrationsDir = __DIR__ . '/database/migrations';
$files = glob($migrationsDir . '/*.php');
sort($files);

if ($isStatus) {
    echo "Status das Migrações:\n";
    echo str_repeat('-', 60) . "\n";
    foreach ($files as $file) {
        $name = basename($file, '.php');
        $status = in_array($name, $executed, true) ? "[APLICADA]" : "[PENDENTE]";
        echo sprintf(" %-12s %s\n", $status, $name);
    }
    echo str_repeat('-', 60) . "\n\n";
    exit(0);
}

// Determina o próximo número de lote
$batchStatement = $pdo->prepare("SELECT MAX(`lote`) FROM `migracoes`");
$batchStatement->execute();
$currentBatch = (int) $batchStatement->fetchColumn();
$nextBatch = $currentBatch + 1;

$appliedCount = 0;
echo "[*] Verificando migrações pendentes...\n";

foreach ($files as $file) {
    $name = basename($file, '.php');

    if (in_array($name, $executed, true)) {
        continue;
    }

    echo "  -> Aplicando: {$name}... ";
    
    $migration = require $file;
    if (is_object($migration) && method_exists($migration, 'up')) {
        try {
            $migration->up($pdo);

            $stmt = $pdo->prepare("INSERT INTO `migracoes` (`migracao`, `lote`) VALUES (:migracao, :lote)");
            $stmt->execute([
                'migracao' => $name,
                'lote'     => $nextBatch
            ]);

            echo "[OK]\n";
            $appliedCount++;
        } catch (Throwable $e) {
            echo "[FALHA]\n";
            echo "\n[ERRO CRÍTICO] Falha ao executar migração '{$name}': " . $e->getMessage() . "\n";
            exit(1);
        }
    }
}

if ($appliedCount === 0) {
    echo "  [i] Nenhuma migração pendente encontrada. Banco de dados está atualizado.\n";
} else {
    echo "\n[OK] {$appliedCount} migração(ões) aplicada(s) com sucesso no Lote {$nextBatch}!\n";
}

// Executa seeds automaticamente se for o primeiro lote de migrações ou se solicitado
$usuariosExistem = false;
try {
    $usersStatement = $pdo->prepare("SELECT COUNT(*) FROM `usuarios`");
    $usersStatement->execute();
    $totalUsuarios = (int) $usersStatement->fetchColumn();
    $usuariosExistem = ($totalUsuarios > 0);
} catch (Throwable $e) {
    $usuariosExistem = false;
}

if (!$usuariosExistem || in_array('--seed', $args, true)) {
    runSeeds($pdo);
}

echo "\n==================================================\n";
echo " Operação finalizada com sucesso.\n";
echo "==================================================\n\n";
