<?php
declare(strict_types=1);

defined('APP_RUNNING') or die('Acesso direto proibido.');

final class PostgresSchema
{
    public static function create(PDO $pdo): void
    {
        $tables = [
            "CREATE TABLE IF NOT EXISTS usuarios (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(120) NOT NULL,
                email VARCHAR(150) NOT NULL UNIQUE,
                senha VARCHAR(255) NOT NULL,
                perfil VARCHAR(20) NOT NULL DEFAULT 'operador' CHECK (perfil IN ('admin', 'operador')),
                status VARCHAR(20) NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
                avatar VARCHAR(255),
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS contas (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(100) NOT NULL,
                instituicao VARCHAR(100),
                tipo VARCHAR(20) NOT NULL DEFAULT 'corrente' CHECK (tipo IN ('corrente', 'poupanca', 'investimento', 'dinheiro', 'outros')),
                saldo_inicial NUMERIC(15,2) NOT NULL DEFAULT 0.00,
                saldo_atual NUMERIC(15,2) NOT NULL DEFAULT 0.00,
                cor VARCHAR(7) NOT NULL DEFAULT '#6F02FF',
                status VARCHAR(20) NOT NULL DEFAULT 'ativa' CHECK (status IN ('ativa', 'inativa')),
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS categorias (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(100) NOT NULL,
                tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('receita', 'despesa')),
                icone VARCHAR(50) NOT NULL DEFAULT 'bi-tag',
                cor VARCHAR(7) NOT NULL DEFAULT '#793CFE',
                status VARCHAR(20) NOT NULL DEFAULT 'ativa' CHECK (status IN ('ativa', 'inativa')),
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS meios_pagamento (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(80) NOT NULL,
                eh_credito SMALLINT NOT NULL DEFAULT 0,
                status VARCHAR(20) NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS transacoes (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
                tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('receita', 'despesa')),
                descricao VARCHAR(255) NOT NULL,
                valor NUMERIC(15,2) NOT NULL,
                data_transacao DATE NOT NULL,
                data_vencimento DATE NOT NULL,
                data_pagamento DATE,
                status VARCHAR(20) NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente', 'pago', 'recebido')),
                conta_id INTEGER REFERENCES contas(id) ON DELETE SET NULL,
                categoria_id INTEGER NOT NULL REFERENCES categorias(id) ON DELETE RESTRICT,
                meio_pagamento_id INTEGER NOT NULL REFERENCES meios_pagamento(id) ON DELETE RESTRICT,
                cartao_credito_id INTEGER,
                fatura_id INTEGER,
                grupo_parcelamento_id VARCHAR(64),
                numero_parcela SMALLINT DEFAULT 1,
                total_parcelas SMALLINT DEFAULT 1,
                observacoes TEXT,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS transferencias (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER NOT NULL REFERENCES usuarios(id) ON DELETE RESTRICT,
                conta_origem_id INTEGER NOT NULL REFERENCES contas(id) ON DELETE RESTRICT,
                conta_destino_id INTEGER NOT NULL REFERENCES contas(id) ON DELETE RESTRICT,
                valor NUMERIC(15,2) NOT NULL,
                data_transferencia DATE NOT NULL,
                observacoes TEXT,
                transacao_origem_id INTEGER,
                transacao_destino_id INTEGER,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS cartoes_credito (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome VARCHAR(100) NOT NULL,
                limite_credito NUMERIC(15,2) NOT NULL DEFAULT 0.00,
                dia_fechamento SMALLINT NOT NULL,
                dia_vencimento SMALLINT NOT NULL,
                conta_padrao_id INTEGER REFERENCES contas(id) ON DELETE SET NULL,
                cor VARCHAR(7) NOT NULL DEFAULT '#3BD7D7',
                status VARCHAR(20) NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                excluido_em TIMESTAMP,
                excluido_por INTEGER
            )",
            "CREATE TABLE IF NOT EXISTS faturas_cartao (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                cartao_credito_id INTEGER NOT NULL REFERENCES cartoes_credito(id) ON DELETE RESTRICT,
                mes_referencia SMALLINT NOT NULL,
                ano_referencia SMALLINT NOT NULL,
                data_fechamento DATE NOT NULL,
                data_vencimento DATE NOT NULL,
                valor_total NUMERIC(15,2) NOT NULL DEFAULT 0.00,
                status VARCHAR(20) NOT NULL DEFAULT 'aberta' CHECK (status IN ('aberta', 'fechada', 'paga')),
                pago_em TIMESTAMP,
                conta_pagamento_id INTEGER REFERENCES contas(id) ON DELETE SET NULL,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
            "CREATE TABLE IF NOT EXISTS auditoria_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id INTEGER REFERENCES usuarios(id) ON DELETE SET NULL,
                tabela VARCHAR(64) NOT NULL,
                registro_id INTEGER NOT NULL,
                acao VARCHAR(20) NOT NULL CHECK (acao IN ('INSERT', 'UPDATE', 'SOFT_DELETE', 'RESTORE', 'PURGE')),
                valores_antigos TEXT,
                valores_novos TEXT,
                endereco_ip VARCHAR(45) NOT NULL,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
            "CREATE TABLE IF NOT EXISTS seguranca_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                evento VARCHAR(80) NOT NULL,
                email VARCHAR(150),
                endereco_ip VARCHAR(45) NOT NULL,
                agente_usuario VARCHAR(255),
                contexto TEXT,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
            "CREATE TABLE IF NOT EXISTS erros_logs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                mensagem TEXT NOT NULL,
                codigo VARCHAR(50),
                arquivo VARCHAR(255),
                linha INTEGER,
                rastreamento TEXT,
                url VARCHAR(255),
                metodo VARCHAR(10),
                endereco_ip VARCHAR(45) NOT NULL,
                usuario_id INTEGER,
                criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
            "CREATE TABLE IF NOT EXISTS configuracoes (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                chave VARCHAR(64) NOT NULL UNIQUE,
                valor TEXT,
                tipo VARCHAR(20) NOT NULL DEFAULT 'string' CHECK (tipo IN ('string', 'integer', 'boolean', 'json')),
                descricao VARCHAR(255),
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
            "CREATE TABLE IF NOT EXISTS migracoes (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                migracao VARCHAR(255) NOT NULL UNIQUE,
                lote INTEGER NOT NULL,
                executado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
            "CREATE TABLE IF NOT EXISTS sessoes (
                id VARCHAR(128) PRIMARY KEY,
                dados TEXT NOT NULL,
                atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )",
        ];

        foreach ($tables as $sql) {
            $pdo->exec($sql);
        }

        $indexes = [
            'CREATE INDEX IF NOT EXISTS idx_usuarios_email ON usuarios (email)',
            'CREATE INDEX IF NOT EXISTS idx_usuarios_status ON usuarios (status)',
            'CREATE INDEX IF NOT EXISTS idx_contas_status ON contas (status)',
            'CREATE INDEX IF NOT EXISTS idx_categorias_tipo ON categorias (tipo)',
            'CREATE INDEX IF NOT EXISTS idx_meios_pagamento_status ON meios_pagamento (status)',
            'CREATE INDEX IF NOT EXISTS idx_trans_data_vencimento ON transacoes (data_vencimento)',
            'CREATE INDEX IF NOT EXISTS idx_trans_status ON transacoes (status)',
            'CREATE INDEX IF NOT EXISTS idx_trans_conta_id ON transacoes (conta_id)',
            'CREATE INDEX IF NOT EXISTS idx_trans_categoria_id ON transacoes (categoria_id)',
            'CREATE INDEX IF NOT EXISTS idx_trans_fatura_id ON transacoes (fatura_id)',
            'CREATE INDEX IF NOT EXISTS idx_trans_excluido_em ON transacoes (excluido_em)',
            'CREATE INDEX IF NOT EXISTS idx_transf_data_transferencia ON transferencias (data_transferencia)',
            'CREATE INDEX IF NOT EXISTS idx_cartoes_status ON cartoes_credito (status)',
            'CREATE INDEX IF NOT EXISTS idx_faturas_periodo ON faturas_cartao (cartao_credito_id, ano_referencia, mes_referencia)',
            'CREATE INDEX IF NOT EXISTS idx_auditoria_tabela_registro ON auditoria_logs (tabela, registro_id)',
            'CREATE INDEX IF NOT EXISTS idx_seg_evento ON seguranca_logs (evento)',
            'CREATE INDEX IF NOT EXISTS idx_seg_ip ON seguranca_logs (endereco_ip)',
            'CREATE INDEX IF NOT EXISTS idx_err_criado_em ON erros_logs (criado_em)',
            'CREATE INDEX IF NOT EXISTS idx_configuracoes_chave ON configuracoes (chave)',
        ];

        foreach ($indexes as $sql) {
            $pdo->exec($sql);
        }

        $foreignKeys = [
            'ALTER TABLE usuarios ADD CONSTRAINT fk_usuarios_excluido_por FOREIGN KEY (excluido_por) REFERENCES usuarios(id) ON DELETE SET NULL',
            'ALTER TABLE contas ADD CONSTRAINT fk_contas_excluido_por FOREIGN KEY (excluido_por) REFERENCES usuarios(id) ON DELETE SET NULL',
            'ALTER TABLE categorias ADD CONSTRAINT fk_categorias_excluido_por FOREIGN KEY (excluido_por) REFERENCES usuarios(id) ON DELETE SET NULL',
            'ALTER TABLE meios_pagamento ADD CONSTRAINT fk_meios_excluido_por FOREIGN KEY (excluido_por) REFERENCES usuarios(id) ON DELETE SET NULL',
            'ALTER TABLE transacoes ADD CONSTRAINT fk_trans_cartao_credito FOREIGN KEY (cartao_credito_id) REFERENCES cartoes_credito(id) ON DELETE SET NULL',
            'ALTER TABLE transacoes ADD CONSTRAINT fk_trans_fatura FOREIGN KEY (fatura_id) REFERENCES faturas_cartao(id) ON DELETE SET NULL',
            'ALTER TABLE transferencias ADD CONSTRAINT fk_transferencias_excluido_por FOREIGN KEY (excluido_por) REFERENCES usuarios(id) ON DELETE SET NULL',
            'ALTER TABLE erros_logs ADD CONSTRAINT fk_erros_usuario FOREIGN KEY (usuario_id) REFERENCES usuarios(id) ON DELETE SET NULL',
        ];

        foreach ($foreignKeys as $sql) {
            try {
                $pdo->exec($sql);
            } catch (PDOException $exception) {
                if ($exception->getCode() !== '42710') {
                    throw $exception;
                }
            }
        }
    }
}
